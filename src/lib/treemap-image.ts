import { layoutFiles } from "@/components/Treemap";
import { scoreColor } from "./score.ts";
import type { Scored } from "./types.ts";

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** Render the heatmap to a standalone SVG string with a title and legend. */
export function treemapSvg(files: Scored[], opts: { title: string; subtitle?: string; width?: number; height?: number }): string {
  const W = opts.width ?? 1600;
  const H = opts.height ?? 1000;
  const pad = 40;
  const headH = 110;
  const { groups, leaves } = layoutFiles(files, W - pad * 2, H - headH - pad);
  const parts: string[] = [];
  parts.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="-apple-system, Segoe UI, Helvetica, Arial, sans-serif">`);
  parts.push(`<rect width="${W}" height="${H}" fill="#0d1117"/>`);
  parts.push(`<text x="${pad}" y="52" font-size="30" font-weight="700" fill="#e6edf3">${esc(opts.title)}</text>`);
  if (opts.subtitle) parts.push(`<text x="${pad}" y="82" font-size="16" fill="#8b949e">${esc(opts.subtitle)}</text>`);
  // legend
  const lx = W - pad - 260;
  parts.push(`<defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" stop-color="${scoreColor(5)}"/><stop offset="0.55" stop-color="${scoreColor(55)}"/><stop offset="1" stop-color="${scoreColor(100)}"/></linearGradient></defs>`);
  parts.push(`<text x="${lx - 8}" y="52" font-size="14" fill="#8b949e" text-anchor="end">safe</text><rect x="${lx}" y="40" width="200" height="14" rx="3" fill="url(#g)"/><text x="${lx + 208}" y="52" font-size="14" fill="#8b949e">critical</text>`);
  parts.push(`<g transform="translate(${pad} ${headH})">`);
  parts.push(`<rect x="0" y="0" width="${W - pad * 2}" height="${H - headH - pad}" fill="#010409" stroke="#30363d"/>`);
  for (const g of groups) {
    parts.push(`<text x="${g.x0 + 4}" y="${g.y0 + 13}" font-size="11" font-family="ui-monospace, Menlo, monospace" fill="#6e7681">${esc(g.data.name)}</text>`);
  }
  for (const d of leaves) {
    const f = { score: d.data.score ?? 0 };
    const w = d.x1 - d.x0;
    const h = d.y1 - d.y0;
    parts.push(`<rect x="${d.x0}" y="${d.y0}" width="${w}" height="${h}" rx="2" fill="${scoreColor(f.score)}"/>`);
    if (w > 70 && h > 26) {
      const name = d.data.name.length * 6.5 > w - 8 ? d.data.name.slice(0, Math.max(3, Math.floor((w - 8) / 6.5) - 1)) + "…" : d.data.name;
      parts.push(`<text x="${d.x0 + 4}" y="${d.y0 + 14}" font-size="11" font-family="ui-monospace, Menlo, monospace" fill="rgba(255,255,255,0.9)">${esc(name)}</text>`);
      if (h > 42) parts.push(`<text x="${d.x0 + 4}" y="${d.y0 + 28}" font-size="10" fill="rgba(255,255,255,0.6)">${f.score}</text>`);
    }
  }
  parts.push(`</g>`);
  parts.push(`<text x="${pad}" y="${H - 14}" font-size="12" fill="#6e7681">Tile size = lines of code. Colour = Orphaned Criticality Score. Generated by Ghost-Architect.</text>`);
  parts.push(`</svg>`);
  return parts.join("");
}

/** Rasterise the SVG in the browser and trigger a PNG download. */
export async function downloadTreemapPng(files: Scored[], opts: { title: string; subtitle?: string; filename?: string }): Promise<void> {
  const svg = treemapSvg(files, opts);
  const blob = new Blob([svg], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  try {
    const img = new Image();
    await new Promise<void>((resolve, reject) => {
      img.onload = () => resolve();
      img.onerror = () => reject(new Error("Could not render the heatmap image"));
      img.src = url;
    });
    const canvas = document.createElement("canvas");
    canvas.width = img.width;
    canvas.height = img.height;
    const ctx = canvas.getContext("2d")!;
    ctx.drawImage(img, 0, 0);
    const png = await new Promise<Blob | null>((r) => canvas.toBlob(r, "image/png"));
    if (!png) throw new Error("PNG encoding failed");
    const a = document.createElement("a");
    a.href = URL.createObjectURL(png);
    a.download = opts.filename ?? "ghost-architect-heatmap.png";
    a.click();
    URL.revokeObjectURL(a.href);
  } finally {
    URL.revokeObjectURL(url);
  }
}
